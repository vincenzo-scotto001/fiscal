// Writes trade_bot/wrangler.toml for deploy, from GitHub repository variables and secrets, and
// creates the Workers KV storage for open positions on the first deploy.
//
//   node scripts/prepare-deploy.mjs --check   only reports whether setup is complete
//   node scripts/prepare-deploy.mjs           checks, creates the storage if needed, writes wrangler.toml
//
// In --check mode it writes ready=true/false to $GITHUB_OUTPUT, so merging before setup is
// finished doesn't fail the workflow.
import { appendFileSync, writeFileSync } from "node:fs";

const VARS = [
  "DISCORD_APP_ID", "DISCORD_PUBLIC_KEY", "DISCORD_GUILD_ID", "OWNER_ID",
  "TRADE_CHANNEL_ID", "INVEST_CHANNEL_ID", "TRADE_ROLE_ID", "INVEST_ROLE_ID",
];
const SECRETS = ["CLOUDFLARE_API_TOKEN", "CLOUDFLARE_ACCOUNT_ID", "DISCORD_BOT_TOKEN", "FINNHUB_API_KEY"];
const KV_TITLE = "fiscal-trade-bot-positions";

const GITHUB_NAME = { OWNER_ID: "DISCORD_OWNER_ID" }; // the name used in GitHub > Settings > Variables

const env = process.env;
const blank = (k) => !String(env[k] || "").trim();
const missingVars = VARS.filter(blank).map((k) => GITHUB_NAME[k] || k);
const missingSecrets = SECRETS.filter(blank);
const ready = missingVars.length === 0 && missingSecrets.length === 0;
const report = [
  missingVars.length ? `variables: ${missingVars.join(", ")}` : "",
  missingSecrets.length ? `secrets: ${missingSecrets.join(", ")}` : "",
].filter(Boolean).join("; ");

if (process.argv.includes("--check")) {
  if (env.GITHUB_OUTPUT) appendFileSync(env.GITHUB_OUTPUT, `ready=${ready}\n`);
  if (ready) console.log("Trade bot setup is complete.");
  else console.log(`::notice::Trade bot not deployed yet. Still missing ${report}. See README > Trade alerts.`);
  process.exit(0);
}
if (!ready) {
  console.error(`Still missing ${report}`);
  process.exit(1);
}

async function cf(path, init = {}) {
  const r = await fetch(`https://api.cloudflare.com/client/v4/accounts/${env.CLOUDFLARE_ACCOUNT_ID}${path}`, {
    ...init,
    headers: { Authorization: `Bearer ${env.CLOUDFLARE_API_TOKEN}`, "Content-Type": "application/json" },
  });
  const data = await r.json().catch(() => ({}));
  if (!r.ok || data.success === false) {
    throw new Error(`Cloudflare ${path} failed (HTTP ${r.status}): ${JSON.stringify(data.errors || data).slice(0, 300)}`);
  }
  return data.result;
}

const namespaces = await cf("/storage/kv/namespaces?per_page=100");
let ns = namespaces.find((n) => n.title === KV_TITLE);
if (!ns) {
  ns = await cf("/storage/kv/namespaces", { method: "POST", body: JSON.stringify({ title: KV_TITLE }) });
  console.log(`Created KV storage "${KV_TITLE}"`);
}

const q = (v) => JSON.stringify(String(v).trim());
writeFileSync("wrangler.toml", `# Generated by scripts/prepare-deploy.mjs during deploy. Don't edit; change the GitHub variables instead.
name = "fiscal-trade-bot"
main = "src/worker.js"
compatibility_date = "2026-10-01"
workers_dev = true

[vars]
DISCORD_APP_ID = ${q(env.DISCORD_APP_ID)}
DISCORD_PUBLIC_KEY = ${q(env.DISCORD_PUBLIC_KEY)}
OWNER_ID = ${q(env.OWNER_ID)}
TRADE_CHANNEL_ID = ${q(env.TRADE_CHANNEL_ID)}
INVEST_CHANNEL_ID = ${q(env.INVEST_CHANNEL_ID)}
TRADE_ROLE_ID = ${q(env.TRADE_ROLE_ID)}
INVEST_ROLE_ID = ${q(env.INVEST_ROLE_ID)}

# Keep logs so problems can be traced: Workers & Pages > fiscal-trade-bot > Logs.
[observability]
enabled = true

[[kv_namespaces]]
binding = "TRADES"
id = ${q(ns.id)}
`);
console.log("Wrote wrangler.toml");
